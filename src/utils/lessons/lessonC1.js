// Métodos para manejar las lecciones
const lessonMethods = {
  getAllLessons() {
    return Object.values(lessons);
  },

  getLesson(id) {
    return lessons[id];
  },

  setLesson(id, lessonData) {
    if (!id.startsWith('C1_')) {
      throw new Error('Invalid lesson ID for this level');
    }
    lessons[id] = {
      ...lessonData,
      id,
      nivel: 'C1'
    };
    return lessons[id];
  },

  deleteLesson(id) {
    if (lessons[id]) {
      delete lessons[id];
      return true;
    }
    return false;
  },

  hasLesson(id) {
    return !!lessons[id];
  },

  getLessonsByLevel() {
    return Object.values(lessons);
  },

  getLessonCount() {
    return Object.keys(lessons).length;
  },

  validateLesson(lessonData) {
    const requiredFields = ['id', 'titulo', 'objetivos', 'contenidos'];
    return requiredFields.every(field => !!lessonData[field]);
  }
};

