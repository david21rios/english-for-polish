export const getIconOptionById = (
  iconId
) => {
  return (
    iconOptions.find(
      (option) =>
        option.id === iconId
    ) || null
  );
};

export const getIconOptionsByCategory = (
  categoryId
) => {
  return iconOptions.filter(
    (option) =>
      option.category ===
      categoryId
  );
};

export const searchIconOptions = (
  searchTerm = ""
) => {
  const normalizedSearch =
    String(searchTerm)
      .trim()
      .toLocaleLowerCase("en-US");

  if (!normalizedSearch) {
    return iconOptions;
  }

  return iconOptions.filter(
    (option) => {
      return (
        option.label
          .toLocaleLowerCase("en-US")
          .includes(normalizedSearch) ||
        option.id.includes(
          normalizedSearch
        ) ||
        option.category.includes(
          normalizedSearch
        )
      );
    }
  );
};